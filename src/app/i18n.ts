export type MessageKey = keyof (typeof MESSAGES)['zh']

export function translate(lang: Lang, key: MessageKey): string {
  const table = MESSAGES[lang] as Record<string, string>
  return table[key] ?? (MESSAGES.zh as Record<string, string>)[key] ?? key
}

/** 把错误码/错误对象转成给用户看的文案（绝不泄露"密钥错误"之外的信息）。 */
export function errorMessageKey(error: unknown): MessageKey {
  const raw = error instanceof Error ? error.message : typeof error === 'string' ? error : ''
  const code = raw.trim()
  const candidates: MessageKey[] = [
    'error.AUTH_FAILED',
    'error.TIMELOCK_NOT_YET',
    'error.TIMELOCK_EXPIRED',
    'error.KEY_NOT_AVAILABLE',
    'error.FORMAT_INVALID',
    'error.KEYFILE_INVALID',
    'error.KEYFILE_PASSWORD_REQUIRED',
    'error.KEYFILE_PASSWORD_WRONG',
    'error.KEYFILE_CHECKSUM_MISMATCH',
    'error.LAYER_COUNT_INVALID',
    'error.UNSUPPORTED_ALGORITHM',
    'error.INVALID_MASTER_KEY_LENGTH',
    'error.INVALID_HEX',
    'error.INVALID_BASE64',
    'error.CSPRNG_UNAVAILABLE',
  ]
  for (const key of candidates) {
    if (key === `error.${code}`) return key
  }
  if (
    code.startsWith('HEADER_') ||
    code.startsWith('MAGIC_') ||
    code.startsWith('BODY_') ||
    code.startsWith('TAG_') ||
    code.startsWith('CHUNK_')
  ) {
    return 'error.FORMAT_INVALID'
  }
  return 'error.UNKNOWN'
}
